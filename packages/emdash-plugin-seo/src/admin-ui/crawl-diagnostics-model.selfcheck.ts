import assert from "node:assert/strict";
import { CRAWL_RESULT_PAGE_SIZE, crawlResultTypes, pageCrawlResults } from "./crawl-diagnostics-model.ts";

const rows = Array.from({ length: 61 }, (_, index) => ({ type: index % 2 ? "posts" : "pages", text: `Entry ${index} /item/${index}` }));
const project = (item: typeof rows[number]) => item;
const all = pageCrawlResults(rows, { query: "", type: "", page: 2 }, project);
assert.equal(all.items.length, CRAWL_RESULT_PAGE_SIZE);
assert.equal(all.start, 26);
assert.equal(all.end, 50);
assert.equal(all.totalCount, 61);
assert.equal(all.filteredCount, 61);
assert.equal(all.pageCount, 3);
const last = pageCrawlResults(rows, { query: "", type: "", page: 99 }, project);
assert.equal(last.page, 3);
assert.equal(last.items.length, 11);
assert.equal(last.end, 61);
const narrowed = pageCrawlResults(rows, { query: " ENTRY 2 ", type: "pages", page: 4 }, project);
assert.deepEqual(narrowed.items.map((row) => row.text), ["Entry 2 /item/2", "Entry 20 /item/20", "Entry 22 /item/22", "Entry 24 /item/24", "Entry 26 /item/26", "Entry 28 /item/28"]);
assert.equal(narrowed.page, 1);
assert.equal(narrowed.totalCount, 61);
assert.equal(narrowed.filteredCount, 6);
const empty = pageCrawlResults(rows, { query: "absent", type: "", page: 0 }, project);
assert.equal(empty.items.length, 0);
assert.equal(empty.start, 0);
assert.equal(empty.end, 0);
assert.equal(empty.page, 1);
assert.deepEqual(crawlResultTypes(rows, (item) => item.type), ["pages", "posts"]);
assert.equal(pageCrawlResults(rows, { query: "", type: "", page: NaN }, project).page, 1);
console.log("Crawl result pagination self-check passed.");
