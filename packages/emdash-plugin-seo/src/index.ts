export const SEO_ADMIN_PAGE = { path: "/seo", label: SEO_DEFAULT_BRAND_NAME, icon: "search" } as const;

/** The admin page entry; its label is the configured name, or a neutral one when branding is unreadable. */
export function seoAdminPage(state: SeoBrandState): { path: "/seo"; label: string; icon: "search" } {
	return { ...SEO_ADMIN_PAGE, label: seoBrandMenuLabel(state) };
}

const seoDescriptor = {
	id: "shipit-seo",
	version: SEO_ENGINE_VERSION,
	format: "native",
	entrypoint: "@shipitseo/emdash-plugin-seo/plugin",
	adminEntry: "@shipitseo/emdash-plugin-seo/admin",
	adminPages: [SEO_ADMIN_PAGE],
	options: {},

	// Draft scores need revision reads; content.get exposes live columns.
	// Network targets are fixed by installation config.
	// The content policy hook only records a public URL before unpublish; it never cancels.
	// Redirect rules stay EmDash records; redirects:write also grants listing them.
	// Taxonomy definitions scope score scans and archive indexing; terms are never written.
	capabilities: [
		"content:read", "content:revisions:read", "network:request", "schema:read",
		"hooks.content-policy:register", "redirects:write", "taxonomies:read",
	],
	allowedHosts: ["api.indexnow.org"],

	storage: {
		// Legacy per-entry SEO overrides, retained only for migration to EmDash core.
		overrides: { indexes: ["ref"] },
		// Social-only exceptions for fields absent from core SEO storage.
		// Search title/description, canonical, image and robots remain core-owned.
		socialOverrides: { indexes: ["ref", "updatedAt"] },
		// Plugin-owned analyzer input. This never writes to EmDash core SEO fields
		// and therefore cannot change emitted page metadata.
		analysisProfiles: { indexes: ["ref", "updatedAt"] },
		// Per-entry robots directives (nofollow/noarchive/nosnippet/noimageindex/
		// notranslate). Extends the emitted robots meta tag; core seo.noIndex stays
		// the only owner of index/noindex.
		metaOverrides: { indexes: ["ref", "updatedAt"] },
		// Per-entry content SEO scores. These are generated by the analyzer and
		// read by admin list badges / inline editor panels.
		scores: { indexes: ["ref", "collection", "score", "updatedAt"] },
		// Monotonic analyzer generations fence older work that finishes after a
		// newer template, module, configuration, or override analysis.
		scoreAnalysisRevisions: { indexes: ["ref", "updatedAt"] },
		// Immutable, deduplicated analyzer snapshots for real score and issue
		// trends. Retention is bounded in the runtime per entry and globally.
		scoreHistory: { indexes: ["ref", "collection", "score", "capturedAt"] },
		// The one current score scan: immutable scope, cursor, pending attempt,
		// counters and bounded receipts, read and fenced by its fixed ID.
		scoreScanJobs: { indexes: [] },
		// Reversible legacy-override -> EmDash core SEO migration journal.
		migrations: { indexes: ["batchId", "ref", "status", "createdAt"] },
		// One bounded recovery record per legacy owner. Prepared handoffs are
		// reconciled by exact ID after an isolate stops between owner writes.
		migrationOperations: { indexes: ["sourceOverrideId", "status", "updatedAt"] },
		// User-defined custom JSON-LD schemas (data only, validated on save).
		// NB: `enabled` is intentionally NOT indexed — it's a boolean, and SQLite
		// cannot bind booleans as index/query values. It's filtered in JS instead.
		schemas: { indexes: ["scope", "createdAt"] },
		// One durable state record per public URL. Delivered records remain available
		// for deduplication and delete notifications; pending/retry records are drained
		// by the plugin's one-shot cron tasks.
		indexnowJobs: { indexes: ["status", "ref", "nextAttemptAt", "updatedAt"] },
		// Bounded operational history. Payloads contain public URLs only; API keys and
		// response bodies are never copied into delivery records.
		indexnowDeliveries: { indexes: ["status", "createdAt"] },
		// One history entry per queue operation with outcome counts and at most three
		// sample URLs. `detail` is a string so SQLite can index and filter it.
		indexnowSubmissions: { indexes: ["status", "source", "detail", "createdAt"] },
		// Full URL lists of longer entries, 100 URLs per record, within a global
		// URL budget; the oldest entry's pages expire as a whole.
		indexnowSubmissionUrls: { indexes: ["submissionId"] },
		// Short-lived cooperative operation leases. Bakery tickets serialize queue
		// drains and migration handoffs across Workerd isolates without exposing a
		// host transaction or lock primitive to sandboxed code.
		operationLeases: { indexes: ["scope", "expiresAt"] },
		// Privacy-minimal 404 monitor. Records contain normalized public paths and
		// aggregate counts only; no IP addresses, query strings, referrers, or user agents.
		notFoundHits: { indexes: ["path", "status", "lastSeenAt", "hits"] },
	},
} satisfies PluginDescriptor;

export interface SeoPluginOptions {
	/** Public HTTPS site origin used for IndexNow key verification. */
	siteUrl?: string;
	/** Written by the Astro entry point `shipitSeo()`; not a site-author option. */
	installation?: SeoPluginInstallation;
}

export interface SeoPluginInstallation {
	/** Origin of Astro's `site` option, also when IndexNow cannot use it. */
	siteOrigin: string | null;
	siteIssue: IndexNowSiteIssue | null;
	keyRoute: IndexNowKeyRoute;
	/** Sitemap ownership and routing facts; absent when installed before sitemap support. */
	sitemap?: SitemapInstallation;
	/** Owner of /robots.txt; absent when installed before robots.txt support. */
	robots?: RobotsInstallation;
	/** Owner of /llms.txt; absent when installed before llms.txt support. */
	llmsTxt?: LlmsTxtInstallation;
	/** Bounded descriptor facts from the Astro adapter; invalid evidence pauses overlap. */
	configuredPlugins?: unknown;
	/** Validated site branding; an unreadable value gives a neutral label and no logo, never an error. */
	branding?: unknown;
	contentAnalysis?: SeoContentAnalysisOptions;
}

const SITE_ISSUES: readonly (IndexNowSiteIssue | null)[] = [null, "missing", "local", "not-https", "path", "port", "not-public"];
const KEY_ROUTES: readonly IndexNowKeyRoute[] = ["injected", "existing", "unavailable"];

function validInstallation(value: unknown, siteUrl: string | undefined): SeoPluginInstallation {
	const candidate = value as Partial<SeoPluginInstallation> | null;
	let origin: string | null = null;
	try { origin = typeof candidate?.siteOrigin === "string" ? new URL(candidate.siteOrigin).origin : null; } catch { origin = null; }
	if (!candidate || typeof candidate !== "object" ||
		!SITE_ISSUES.includes(candidate.siteIssue ?? null) || candidate.siteIssue === undefined ||
		!KEY_ROUTES.includes(candidate.keyRoute as IndexNowKeyRoute) ||
		(candidate.siteOrigin !== null && candidate.siteOrigin !== origin) ||
		(siteUrl === undefined) === (candidate.siteIssue === null) ||
		(siteUrl !== undefined && candidate.siteOrigin !== indexNowSiteOriginUrl(siteUrl).origin) ||
		(candidate.sitemap !== undefined && validSitemapInstallation(candidate.sitemap) === null) ||
		(candidate.robots !== undefined && validRobotsInstallation(candidate.robots) === null) ||
		(candidate.llmsTxt !== undefined && validLlmsTxtInstallation(candidate.llmsTxt) === null))
		throw new Error("SEO plugin installation options are invalid. Configure the plugin with shipitSeo().");
	return {
		siteOrigin: candidate.siteOrigin ?? null,
		siteIssue: candidate.siteIssue,
		keyRoute: candidate.keyRoute as IndexNowKeyRoute,
		...(candidate.sitemap !== undefined ? { sitemap: validSitemapInstallation(candidate.sitemap)! } : {}),
		...(candidate.robots !== undefined ? { robots: validRobotsInstallation(candidate.robots)! } : {}),
		...(candidate.llmsTxt !== undefined ? { llmsTxt: validLlmsTxtInstallation(candidate.llmsTxt)! } : {}),
		...(candidate.configuredPlugins !== undefined ? { configuredPlugins: candidate.configuredPlugins } : {}),
		...(candidate.branding !== undefined ? { branding: candidate.branding } : {}),
		...(candidate.contentAnalysis !== undefined ? { contentAnalysis: checkContentAnalysisOptions(candidate.contentAnalysis) } : {}),
	};
}

/** Branding recorded by the Astro entry point; it never throws, so public metadata keeps working. */
export function seoBranding(options: SeoPluginOptions = {}): SeoBrandState {
	const installation = options.installation as { branding?: unknown } | null | undefined;
	return seoBrandState(installation && typeof installation === "object" ? installation.branding : undefined);
}

export function seoPlugin(options: SeoPluginOptions = {}): PluginDescriptor {
	const installation = options.installation === undefined ? undefined : validInstallation(options.installation, options.siteUrl);
	if (options.siteUrl === undefined && installation === undefined) return seoDescriptor;
	const hostname = options.siteUrl === undefined ? null : indexNowSiteOriginUrl(options.siteUrl).hostname;
	return {
		...seoDescriptor,
		adminPages: [seoAdminPage(seoBranding(options))],
		options: {
			...(options.siteUrl === undefined ? {} : { siteUrl: options.siteUrl }),
			...(installation ? { installation } : {}),
		},
		allowedHosts: hostname ? [...new Set([...seoDescriptor.allowedHosts, hostname])] : [...seoDescriptor.allowedHosts],
	};
}

/** The IndexNow installation facts the native runtime gives the engine. */
export function seoInstallation(options: SeoPluginOptions = {}): IndexNowInstallation {
	const siteUrl = options.siteUrl === undefined ? null : indexNowSiteOriginUrl(options.siteUrl).origin;
	if (options.installation === undefined) {
		return { mode: "legacy", siteUrl, siteOrigin: siteUrl, siteIssue: null, keyRoute: null };
	}
	const installation = validInstallation(options.installation, options.siteUrl);
	return { mode: "astro", siteUrl, siteOrigin: installation.siteOrigin, siteIssue: installation.siteIssue, keyRoute: installation.keyRoute };
}

/** Sitemap facts from the Astro entry point; null for installations without them. */
export function seoSitemapInstallation(options: SeoPluginOptions = {}): SitemapInstallation | null {
	if (options.installation === undefined) return null;
	return validInstallation(options.installation, options.siteUrl).sitemap ?? null;
}

/** Robots.txt ownership facts from the Astro entry point; null for installations without them. */
export function seoRobotsInstallation(options: SeoPluginOptions = {}): RobotsInstallation | null {
	if (options.installation === undefined) return null;
	return validInstallation(options.installation, options.siteUrl).robots ?? null;
}

/** llms.txt ownership facts from the Astro entry point; null for installations without them. */
export function seoLlmsTxtInstallation(options: SeoPluginOptions = {}): LlmsTxtInstallation | null {
	if (options.installation === undefined) return null;
	return validInstallation(options.installation, options.siteUrl).llmsTxt ?? null;
}
